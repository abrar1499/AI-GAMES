#!/usr/bin/env python3
"""Reads BolKhata's item rules, r(Cat.X, "Label", "word", ...), into ItemWords.kt: each item's spoken words."""
import re, sys, json
src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8').read()
items = {}
for m in re.finditer(r'\br\(Cat\.[A-Z_]+,\s*"([^"]+)"((?:\s*,\s*"[^"]*")+)\s*\)', text):
    label, rest = m.group(1), re.findall(r'"([^"]*)"', m.group(2))
    items.setdefault(label, [])
    for w in rest:
        if w and w not in items[label]: items[label].append(w)
lines = ['// Generated by tools/item_words.py from BolKhata\'s Parser.kt. Do not edit by hand.',
         'package com.boltamunshi.app', '',
         '/** The words people say for each item BolKhata knows, as written in its parser. */',
         'internal object ItemWords {', '    val words: Map<String, List<String>> = mapOf(']
lines += ['        ' + json.dumps(k, ensure_ascii=False) + ' to listOf(' + ', '.join(json.dumps(w, ensure_ascii=False) for w in v) + '),' for k, v in items.items()]
lines += ['    )', '}', '']
open(out, 'w', encoding='utf-8').write('\n'.join(lines))
print(len(items), 'items')
